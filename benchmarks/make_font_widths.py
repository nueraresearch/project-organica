"""Generate ``benchmarks/helvetica_widths.json`` from the Adobe AFM metrics.

The PDF standard fonts are the base-14 fonts, and their advance widths are
not built into PDF: a text-showing operator needs them, and the only correct
source is Adobe's own AFM.  The AFM files for the Helvetica family ship with
matplotlib (``mpl-data/fonts/pdfcorefonts``), which redistributes Adobe's
originals verbatim.

Widths are committed as a data file so the figure build is stdlib-only and
reproducible offline; this generator is how that file was produced, and it
records where the numbers came from.

    python benchmarks/make_font_widths.py
"""

from __future__ import annotations

import json
import re
import sys
import urllib.request
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "benchmarks" / "helvetica_widths.json"

BASE = ("https://raw.githubusercontent.com/matplotlib/matplotlib/main/lib/"
        "matplotlib/mpl-data/fonts/pdfcorefonts/")
FONTS = ("Helvetica", "Helvetica-Bold")

LINE = re.compile(r"^C\s+(-?\d+)\s*;\s*WX\s+(-?\d+)\s*;\s*N\s+(\S+)\s*;")


def fetch(name: str) -> str:
    with urllib.request.urlopen(BASE + name + ".afm", timeout=60) as response:
        return response.read().decode("latin-1")


def widths(afm: str) -> dict[str, int]:
    """Advance width per byte code, in 1/1000 em."""
    out: dict[str, int] = {}
    for line in afm.splitlines():
        match = LINE.match(line.strip())
        if not match:
            continue
        code, wx = int(match.group(1)), int(match.group(2))
        if 0 <= code <= 255:
            out[str(code)] = wx
    return out


def main() -> int:
    table = {}
    for name in FONTS:
        table[name] = widths(fetch(name))
        print("%-16s %d widths" % (name, len(table[name])))
    payload = {
        "_source": BASE,
        "_provenance": ("Adobe AFM metrics for the Helvetica family, "
                        "redistributed verbatim in matplotlib's "
                        "mpl-data/fonts/pdfcorefonts. Widths are in 1/1000 em. "
                        "Generated by benchmarks/make_font_widths.py."),
        "_fonts": table,
    }
    OUT.write_text(json.dumps(payload, indent=1, sort_keys=True) + "\n",
                   encoding="utf-8")
    print("wrote %s" % OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
